const DICTS = { zh: ZH, en: EN }

function readStored(key, allowed) {
  try {
    const value = window.localStorage.getItem(key)
    if (allowed.includes(value)) return value
  } catch {
    // ignore
  }
  return null
}

function detectLocale() {
  const language = typeof navigator === 'undefined' ? '' : navigator.language || ''
  return language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export function interpolate(template, vars) {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name) => (
    vars[name] == null ? '' : String(vars[name])
  ))
}

export function translate(locale, key, vars) {
  const table = DICTS[locale] || ZH
  const template = table[key] ?? ZH[key] ?? key
  return interpolate(template, vars)
}

function applyDocumentPrefs(theme, locale) {
  const root = document.documentElement
  root.setAttribute('data-theme', theme)
  root.lang = locale === 'zh' ? 'zh-CN' : 'en'
  document.title = translate(locale, 'app.title')
}

const PrefsContext = createContext(null)

export function PrefsProvider({ children }) {
  const [theme, setThemeState] = useState(() => readStored(THEME_STORAGE_KEY, ['dark', 'light']) || 'dark')
  const [locale, setLocaleState] = useState(() => readStored(LOCALE_STORAGE_KEY, ['zh', 'en']) || detectLocale())

  useEffect(() => {
    applyDocumentPrefs(theme, locale)
  }, [theme, locale])

  const setTheme = useCallback((next) => {
    const value = next === 'light' ? 'light' : 'dark'
    setThemeState(value)
    try {
      window.localStorage.setItem(THEME_STORAGE_KEY, value)
    } catch {
      // ignore
    }
  }, [])

  const setLocale = useCallback((next) => {
    const value = next === 'en' ? 'en' : 'zh'
    setLocaleState(value)
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, value)
    } catch {
      // ignore
    }
  }, [])

  const t = useCallback((key, vars) => translate(locale, key, vars), [locale])

  const value = useMemo(() => ({
    theme,
    locale,
    setTheme,
    setLocale,
    t,
  }), [theme, locale, setTheme, setLocale, t])

  return <PrefsContext.Provider value={value}>{children}</PrefsContext.Provider>
}

export function useI18n() {
  const ctx = useContext(PrefsContext)
  if (ctx) return ctx
  return {
    theme: 'dark',
    locale: 'zh',
    setTheme: () => {},
    setLocale: () => {},
    t: (key, vars) => translate('zh', key, vars),
  }
}
